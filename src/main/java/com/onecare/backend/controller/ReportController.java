package com.onecare.backend.controller;

import com.onecare.backend.dto.ApiResponse;
import com.onecare.backend.dto.response.ClinicReportResponse;
import com.onecare.backend.dto.response.PharmacyReportResponse;
import com.onecare.backend.enums.ReportFormat;
import com.onecare.backend.exception.BusinessRuleException;
import com.onecare.backend.security.Permission;
import com.onecare.backend.service.ReportService;

import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.security.SecurityRequirement;
import io.swagger.v3.oas.annotations.tags.Tag;

import org.springframework.format.annotation.DateTimeFormat;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import java.time.LocalDate;
import java.util.Locale;

/**
 * Clinic and pharmacy reports (FR039/FR040, UC24/UC25). Read-only aggregation
 * over DDP-20/21/22/25/30; no report entity is persisted, so exports happen on
 * the same endpoints via {@code format=csv|pdf} rather than a
 * /reports/{id}/export resource.
 *
 * <p>RBAC per SDS Table 9 (AC7): clinic reports are generated by
 * SUPER_ADMIN/ADMIN, pharmacy reports by SUPER_ADMIN/PHARMACIST.</p>
 */
@Tag(name = "Reports", description = "Clinic and pharmacy report generation and export APIs")
@SecurityRequirement(name = "bearerAuth")
@RestController
@RequestMapping("/api/reports")
public class ReportController {

    private final ReportService reportService;

    public ReportController(ReportService reportService) {
        this.reportService = reportService;
    }

    @Operation(summary = "Generate the clinic report (FR039, UC24)",
            description = "Patient, consultation and queue aggregates over a date range "
                    + "(optionally narrowed to one doctor). Add format=csv or format=pdf "
                    + "to download the exact same data as a file (AC5).")
    @GetMapping("/clinic")
    @PreAuthorize("hasAuthority('" + Permission.REPORT_CLINIC_GENERATE + "')")
    public ResponseEntity<?> getClinicReport(
            @Parameter(description = "Range start (inclusive), yyyy-MM-dd")
            @RequestParam(required = false) @DateTimeFormat(iso = DateTimeFormat.ISO.DATE)
            LocalDate from,
            @Parameter(description = "Range end (inclusive), yyyy-MM-dd - at most 1 year after from")
            @RequestParam(required = false) @DateTimeFormat(iso = DateTimeFormat.ISO.DATE)
            LocalDate to,
            @Parameter(description = "Optional doctor user id to narrow the report")
            @RequestParam(required = false) Long doctorId,
            @Parameter(description = "Export format: csv or pdf (default: on-screen JSON)")
            @RequestParam(required = false) String format) {

        ReportFormat reportFormat = parseFormat(format);
        if (reportFormat == ReportFormat.JSON) {
            ClinicReportResponse report = reportService.getClinicReport(from, to, doctorId);
            return ResponseEntity.ok(new ApiResponse<>(true, "Clinic report generated successfully", report));
        }
        return fileResponse(reportService.exportClinicReport(from, to, doctorId, reportFormat));
    }

    @Operation(summary = "Generate the pharmacy report (FR040, UC25)",
            description = "One of type=stock-usage|expiry|dispensing-history over a date range "
                    + "(max 1 year). Add format=csv or format=pdf to download the exact same "
                    + "data as a file (AC5).")
    @GetMapping("/pharmacy")
    @PreAuthorize("hasAuthority('" + Permission.REPORT_PHARMACY_GENERATE + "')")
    public ResponseEntity<?> getPharmacyReport(
            @Parameter(description = "Report type: stock-usage, expiry or dispensing-history",
                    required = true)
            @RequestParam(required = false) String type,
            @Parameter(description = "Range start (inclusive), yyyy-MM-dd")
            @RequestParam(required = false) @DateTimeFormat(iso = DateTimeFormat.ISO.DATE)
            LocalDate from,
            @Parameter(description = "Range end (inclusive), yyyy-MM-dd - at most 1 year after from")
            @RequestParam(required = false) @DateTimeFormat(iso = DateTimeFormat.ISO.DATE)
            LocalDate to,
            @Parameter(description = "Export format: csv or pdf (default: on-screen JSON)")
            @RequestParam(required = false) String format) {

        ReportFormat reportFormat = parseFormat(format);
        if (reportFormat == ReportFormat.JSON) {
            PharmacyReportResponse report = reportService.getPharmacyReport(type, from, to);
            return ResponseEntity.ok(new ApiResponse<>(true, "Pharmacy report generated successfully", report));
        }
        return fileResponse(reportService.exportPharmacyReport(type, from, to, reportFormat));
    }

    private ReportFormat parseFormat(String format) {
        if (format == null || format.isBlank() || "json".equalsIgnoreCase(format.trim())) {
            return ReportFormat.JSON;
        }
        try {
            return ReportFormat.valueOf(format.trim().toUpperCase(Locale.ROOT));
        } catch (IllegalArgumentException ex) {
            throw new BusinessRuleException(
                    "Unknown export format '" + format + "'. Allowed values: csv, pdf");
        }
    }

    private ResponseEntity<byte[]> fileResponse(ReportService.ReportFile file) {
        return ResponseEntity.ok()
                .header(HttpHeaders.CONTENT_DISPOSITION, "attachment; filename=\"" + file.filename() + "\"")
                .contentType(MediaType.parseMediaType(file.contentType()))
                .contentLength(file.content().length)
                .body(file.content());
    }
}
